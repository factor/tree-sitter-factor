// Keep the scanner's reserved-word table in sync with grammar.js.
const fs = require('node:fs');
const grammar = JSON.parse(fs.readFileSync('src/grammar.json', 'utf8'));
const reserved = new Set();
function visit(rule) {
  if (!rule || typeof rule !== 'object') return;
  if (rule.type === 'STRING') reserved.add(rule.value);
  for (const value of Object.values(rule)) {
    if (Array.isArray(value)) value.forEach(visit);
    else if (value && typeof value === 'object') visit(value);
  }
}
visit(grammar.rules);
const result = '// Generated by scripts/generate-reserved.js. Do not edit.\n' +
  'static const char *const RESERVED_WORDS[] = {\n' +
  [...reserved].sort().map(word => `  ${JSON.stringify(word)},`).join('\n') + '\n};\n';
fs.writeFileSync('src/reserved.h', result);
